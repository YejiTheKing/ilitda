"""가상 사업장 자료를 만든다.

사업장: 소규모 부품 가공 업체(가상). 업무: 신규 거래처 등록부터 첫 견적서 발행까지.
전임 담당자가 남긴 파일을 흉내 낸다. 구버전·최신본이 섞여 있고, 메모끼리 내용이 어긋나는 곳이 있다.
모든 이름·번호·금액은 지어낸 것이다.

사용: .venv/bin/python scripts/make_sample.py
"""
from pathlib import Path

import docx
import openpyxl

OUT = Path("data/sample/거래처등록_견적")


def write_docx(path, title, paragraphs, table=None):
    d = docx.Document()
    d.add_heading(title, level=1)
    for p in paragraphs:
        d.add_paragraph(p)
    if table:
        t = d.add_table(rows=0, cols=len(table[0]))
        t.style = "Table Grid"
        for row in table:
            cells = t.add_row().cells
            for c, v in zip(cells, row):
                c.text = v
    d.save(path)


def main():
    OUT.mkdir(parents=True, exist_ok=True)

    # 견적서 양식 구버전 (2024): 유효기간 30일, 결제조건 없음
    write_docx(OUT / "견적서 양식.docx", "견 적 서", [
        "문서번호: Q-____-___",
        "수신: ______ 귀중",
        "견적일자: 20__년 __월 __일",
        "유효기간: 견적일로부터 30일",
        "납품조건: 당사 출고 기준",
        "아래와 같이 견적합니다.",
    ], [["품명", "규격", "수량", "단가", "금액"], ["", "", "", "", ""]])

    # 견적서 양식 최신본 (2025.03 개정): 유효기간 14일, 결제조건·담당자 연락처 항목 추가, 문서번호 체계 변경
    write_docx(OUT / "견적서 양식_수정.docx", "견 적 서", [
        "문서번호: Q-2025-____ (연도-일련번호)",
        "수신: ______ 귀중",
        "견적일자: 20__년 __월 __일",
        "유효기간: 견적일로부터 14일",
        "결제조건: 납품 후 30일 이내 현금 결제",
        "납품조건: 당사 출고 기준",
        "담당자: ______ (연락처 기재)",
        "아래와 같이 견적합니다.",
        "※ 2025.03 개정: 유효기간 단축, 결제조건 명기",
    ], [["품명", "규격", "수량", "단가", "금액", "비고"], ["", "", "", "", "", ""]])

    # 거래처 등록 체크리스트 (최신)
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "거래처등록"
    ws.append(["순서", "확인 항목", "필수", "담당"])
    rows = [
        (1, "사업자등록증 사본 수령", "필수", "영업"),
        (2, "사업자등록번호 국세청 조회로 휴폐업 확인", "필수", "영업"),
        (3, "거래처 등록 요청서 작성", "필수", "영업"),
        (4, "대표 승인", "필수", "대표"),
        (5, "회계 프로그램에 거래처 코드 등록", "필수", "경리"),
        (6, "통장 사본 수령 (매입 거래처만)", "조건부", "경리"),
    ]
    for r in rows:
        ws.append(list(r))
    wb.save(OUT / "거래처등록_체크리스트.xlsx")

    # 절차 메모 (구버전, 2024): 체크리스트와 어긋나는 부분이 있음 — 메일 승인(폐지된 방식), 유효기간 30일
    (OUT / "견적 업무 메모.txt").write_text("""견적 업무 메모 (2024.05 작성)

1. 거래처가 처음이면 사업자등록증부터 받는다.
2. 회계 프로그램에 거래처 코드를 만든다. (코드는 영업이 직접 만듦)
3. 견적서 양식에 품명/수량/단가를 채운다. 유효기간은 30일.
4. 대표님께 메일로 보내고 확인받은 뒤 거래처에 발송한다.
5. 발송한 견적서는 '견적서 발송대장'에 적는다.

* 단가는 단가표 최신본을 쓸 것.
""", encoding="utf-8")

    # 인수인계 메모 (최신, 2025.06, 미완성): 변경된 내용 일부만 적혀 있음
    (OUT / "인수인계 메모_작성중.txt").write_text("""인수인계 메모 (2025.06, 작성 중)

- 견적서 양식이 바뀜 → '견적서 양식_수정' 파일 사용. 옛날 양식 쓰면 안 됨.
- 거래처 코드는 이제 경리가 등록함. 영업은 등록 요청서만 작성.
- 견적서 발송 전에 대표 승인 필수 (메일 말고 결재 시스템에서).
- 발송대장은 2025년부터 엑셀 '견적서 발송대장_2025'로 바뀜.
- 단가표: (여기까지 쓰다 맒)
""", encoding="utf-8")

    # 처리 기록 2건 (가상 고객). 하나는 구버전 양식, 하나는 최신 양식으로 작성됨
    write_docx(OUT / "견적서_Q-2024-031_가온정밀.docx", "견 적 서", [
        "문서번호: Q-2024-031",
        "수신: 가온정밀(가상) 귀중",
        "견적일자: 2024년 11월 4일",
        "유효기간: 견적일로부터 30일",
        "납품조건: 당사 출고 기준",
    ], [["품명", "규격", "수량", "단가", "금액"], ["브래킷 A", "SUS304 t3", "200", "4,500", "900,000"]])

    write_docx(OUT / "견적서_Q-2025-012_한빛테크.docx", "견 적 서", [
        "문서번호: Q-2025-012",
        "수신: 한빛테크(가상) 귀중",
        "견적일자: 2025년 5월 20일",
        "유효기간: 견적일로부터 14일",
        "결제조건: 납품 후 30일 이내 현금 결제",
        "납품조건: 당사 출고 기준",
        "담당자: 김담당 (연락처 기재)",
    ], [["품명", "규격", "수량", "단가", "금액", "비고"], ["브래킷 B", "SUS304 t5", "100", "6,200", "620,000", "도면 rev.2"]])

    # 발송대장 (최신 엑셀)
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "2025"
    ws.append(["발송일", "문서번호", "거래처", "금액", "승인", "비고"])
    ws.append(["2025-05-20", "Q-2025-012", "한빛테크(가상)", 620000, "대표 승인(결재)", ""])
    wb.save(OUT / "견적서 발송대장_2025.xlsx")

    # 사본 (내용 동일) — 사본 묶기 확인용
    import shutil
    shutil.copy(OUT / "견적서 양식_수정.docx", OUT / "견적서 양식_수정 - 복사본.docx")

    # 읽지 못하는 파일 — 건너뛰기 확인용
    (OUT / "단가표_2023.hwp").write_bytes(b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1" + b"\x00" * 64)

    print(f"{OUT}: {len(list(OUT.iterdir()))}개 파일")


if __name__ == "__main__":
    main()
