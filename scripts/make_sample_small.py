from pathlib import Path

import docx
import openpyxl

OUT = Path("data/sample/출장비_정산")


def write_docx(path, title, paragraphs, table=None):
    d = docx.Document()
    d.add_heading(title, level=1)
    for p in paragraphs:
        d.add_paragraph(p)
    if table:
        t = d.add_table(rows=0, cols=len(table[0]))
        t.style = "Table Grid"
        for row in table:
            cells = t.add_row().cells
            for c, v in zip(cells, row):
                c.text = v
    d.save(path)


